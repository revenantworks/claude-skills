        self.skill(proj / ".claude" / "skills" / "scoped", "scoped", "project")
        acct = us / "synced" / "acct"
        for n, body in [("twin-stale", "old"), ("twin-off", "same"), ("twin-open", "same"),
                        ("retired-one", "r"), ("companion", "c"), ("pdf", "p")]:
            self.skill(acct / n, n, body)
        man = [{"name": n, "source": "plugin", "creatorType": "user"}
               for n in ("twin-stale", "twin-off", "twin-open", "retired-one", "companion")]
