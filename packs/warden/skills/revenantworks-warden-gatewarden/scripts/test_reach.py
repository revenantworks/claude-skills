    def skill(self, folder: Path, name: str, body: str = "same", fm: str | None = None):
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "SKILL.md").write_text(f"---\nname: {fm or name}\ndescription: d\n---\n{self.MARK} {body}\n",
                                         encoding="utf-8")

